function translateStem(stem) {
  if (names[stem]) return names[stem];
  if (stem.endsWith('-hold')) {
    const base = translateStem(stem.slice(0, -5));
    if (base) return `${base} — isometria`;
  }
  for (const [prefix, qualifier] of prefixes) {
    if (stem.startsWith(prefix)) {
      const base = translateStem(stem.slice(prefix.length));
      if (base) return `${base} (${qualifier})`;
    }
  }
  return null;
}

function displayName(filename) {
  const stem = filename.replace(/\.[^.]+$/, '').toLowerCase();
  const phase = stem.match(/-(main|start|peak)$/)?.[1];
  const base = phase ? stem.slice(0, -(phase.length + 1)) : stem;
  const translated = translateStem(base);
  const name = translated ?? base.replace(/[-_]+/g, ' ').replace(/^./, (char) => char.toUpperCase());
  const suffix = { start: 'posição inicial', peak: 'posição final', main: 'visão geral' }[phase];
  return suffix ? `${name} — ${suffix}` : name;
}

